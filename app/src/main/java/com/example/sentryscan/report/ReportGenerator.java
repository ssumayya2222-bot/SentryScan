package com.example.sentryscan.report;

import android.content.Context;

import com.example.sentryscan.model.CveEntry;
import com.example.sentryscan.model.OpenPort;
import com.example.sentryscan.model.ScanResult;
import com.example.sentryscan.scanner.VulnerabilityMatcher;

import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStreamWriter;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Locale;

public class ReportGenerator {

    private final Context context;
    private final VulnerabilityMatcher matcher;

    public ReportGenerator(Context context) {
        this.context = context;
        this.matcher = new VulnerabilityMatcher(context);
    }

    // Writes the report file and returns it
    public File generate(ScanResult result) throws IOException {
        File dir = new File(context.getFilesDir(), "reports");
        if (!dir.exists()) {
            dir.mkdirs();
        }
        File file = new File(dir, "SentryScan_report_" + result.getId() + ".html");
        try (OutputStreamWriter w = new OutputStreamWriter(
                new FileOutputStream(file), StandardCharsets.UTF_8)) {
            w.write(buildHtml(result));
        }
        return file;
    }

    private String buildHtml(ScanResult result) {
        StringBuilder h = new StringBuilder();
        h.append("<html><head><meta charset='utf-8'>");
        h.append("<meta name='viewport' content='width=device-width, initial-scale=1'>");
        h.append("<title>SentryScan Report</title></head>");
        h.append("<body style='font-family:sans-serif;margin:16px'>");
        h.append("<h1>SentryScan Vulnerability Report</h1>");
        h.append("<p><b>Target:</b> ").append(esc(result.getTarget())).append("<br>");
        h.append("<b>Date:</b> ").append(esc(result.getDate())).append("<br>");
        h.append("<b>Overall risk:</b> ").append(badge(result.getRiskLevel())).append("<br>");
        h.append("<b>Open ports:</b> ").append(result.getOpenPorts().size()).append("</p>");

        if (result.getOpenPorts().isEmpty()) {
            h.append("<p>No open ports were found among the scanned ports.</p>");
        }

        for (OpenPort p : result.getOpenPorts()) {
            h.append("<hr><h3>Port ").append(p.getPort())
                    .append(" (").append(esc(p.getService())).append(")</h3>");
            String banner = p.getBanner();
            h.append("<p><b>Banner:</b> ")
                    .append(banner == null || banner.isEmpty() ? "(none)" : esc(banner))
                    .append("</p>");

            List<CveEntry> hits = matcher.match(banner);
            if (hits.isEmpty()) {
                h.append("<p>No known vulnerabilities found in the local database.</p>");
            } else {
                h.append("<ul>");
                for (CveEntry c : hits) {
                    h.append("<li>").append(badge(c.getSeverity())).append(" <b>")
                            .append(esc(c.getCveId())).append("</b>: ")
                            .append(esc(c.getDescription())).append("</li>");
                }
                h.append("</ul>");
            }
        }
        h.append("<hr><p style='color:gray'>Generated by SentryScan. ");
        h.append("Matching uses a local vulnerability database, so it is not exhaustive.</p>");
        h.append("</body></html>");
        return h.toString();
    }

    // A small colored label for a severity word
    private String badge(String severity) {
        String color;
        switch (severity == null ? "" : severity.toLowerCase(Locale.ROOT)) {
            case "critical": color = "#b71c1c"; break;
            case "high": color = "#e65100"; break;
            case "medium": color = "#f9a825"; break;
            default: color = "#2e7d32"; break;
        }
        return "<span style='color:white;background:" + color
                + ";padding:2px 8px;border-radius:4px'>" + esc(severity) + "</span>";
    }

    // Stop banner text from being read as HTML
    private String esc(String s) {
        if (s == null) return "";
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }
}